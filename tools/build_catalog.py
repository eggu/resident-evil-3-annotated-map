"""Per-location RE3 catalog: data/room-catalog.json + docs/room-catalog.md.

Sources: SCD room scripts (DATA_J, live code paths only), room ids -> Evil Resource names
(data/room-ids.json), item names (data/item-names-en.json, SDK slot table).
RE3 SCE ids differ from biorand's RE2-derived labels: decompiler SCE_MOVE = typewriter,
SCE_SAVE = item box (verified against Evil Resource in 14/15 save rooms).
FLAG_CHG with data[0] == 44 is an item-use point; data[2] is the required item.
"""
import json, collections
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_room_data import const_items, item_id

ROOT = Path(__file__).resolve().parents[1]
NPC = ('CARLOS', 'NIKOLAI', 'MIKHAIL', 'JILL', 'BRAD_VICKERS', 'DARIO_ROSSO', 'MARVIN', 'TYRELL', 'MURPHY',
       'PROMO_GIRL', 'NIKOLAI_DEAD')


def tags(cond):
    t = []
    for c in cond:
        if '(0, 23, 0)' in c:
            t.append('Easy' if c.startswith('else') else 'Hard')
        elif '(0, 23, 1)' in c:
            t.append('Hard' if c.startswith('else') else 'Easy')
        elif 'ck(48,' in c.replace(' ', '').replace('ck(48,', 'ck(48,'):
            t.append('random')
        else:
            t.append('story')
    return sorted(set(t))


def main():
    ids = json.loads((ROOT / 'data/room-ids.json').read_text())
    er = {r['key']: r for r in json.loads((ROOT / 'data/evilresource-rooms.json').read_text())}
    names = json.loads((ROOT / 'data/item-names-en.json').read_text())
    rooms = json.loads((ROOT / 'data/rooms-DATA_J.json').read_text())
    table = const_items()
    by = collections.defaultdict(list)
    for rid, k in ids.items():
        by[k].append(rid)
    cat = []
    for key in sorted(by, key=lambda k: min(by[k])):
        loc = dict(key=key, name=er[key]['title'].split(' (')[0], rdts=sorted(by[key]), items=[], files=[], maps=[],
                   key_doors=[], locked_doors=[], puzzles=[], typewriters=[], item_boxes=[], enemies=collections.Counter())
        for rid in loc['rdts']:
            r = rooms[rid]
            for i in r['items']:
                if i['path'] is None:
                    continue
                e = dict(rdt=rid, name=i['name'], amount=i['amount'], flag=i['flag'], x=i['x'], z=i['z'], tags=tags(i['cond']))
                if i['name'] == 'Ink Ribbon':
                    e['tags'] = sorted(set(e['tags']) | {'Hard'})
                (loc['maps'] if i['item'] >= 0xA4 and i['name'].endswith('Map') else
                 loc['files'] if 0x86 <= i['item'] <= 0xA3 else loc['items']).append(e)
            for d in r['doors']:
                if d['path'] is None:
                    continue
                if 0 < d['key'] < 254:
                    loc['key_doors'].append(dict(rdt=rid, to=d['target'], key=names[d['key']], lock_id=d['lock_id']))
                elif d['key'] == 255:
                    loc['locked_doors'].append(dict(rdt=rid, to=d['target'], lock_id=d['lock_id']))
            for a in r['aots']:
                if a['path'] is None:
                    continue
                if a['sce'] == 'SCE_MOVE':
                    loc['typewriters'].append(dict(rdt=rid, x=a['x'], z=a['z']))
                elif a['sce'] == 'SCE_SAVE':
                    loc['item_boxes'].append(dict(rdt=rid, x=a['x'], z=a['z']))
                elif a['sce'] == 'SCE_FLAG_CHG' and a['data'][0] == 44:
                    loc['puzzles'].append(dict(rdt=rid, item=names[item_id(a['data'][2], table)], x=a['x'], z=a['z']))
            for e in r['enemies']:
                t = e['type'].replace('ENEMY_', '')
                if e['path'] is not None and not t.startswith(NPC):
                    loc['enemies'][t] += 1
        loc['enemies'] = dict(loc['enemies'])
        cat.append(loc)
    (ROOT / 'data/room-catalog.json').write_text(json.dumps(cat, indent=1, ensure_ascii=False) + '\n')
    md = ['# RE3 room catalog', '', 'Generated by `tools/build_catalog.py` from DATA_J room scripts (live code paths). '
          'Tags: Easy/Hard = difficulty (bank0 bit23), random = bank48 50% choice, story = other flag guard. '
          'Enemy counts are em_set entries across all variants and branches, not simultaneous spawns.', '']
    for c in cat:
        md.append(f"## {c['name']} — {', '.join('R' + r for r in c['rdts'])}")
        def fmt(xs):
            return '; '.join(f"{x['name']}" + (f" ×{x['amount']}" if x.get('amount', 1) > 1 else '') +
                             (f" [{'/'.join(x['tags'])}]" if x['tags'] else '') for x in xs)
        for label, k in (('Items', 'items'), ('Files', 'files'), ('Maps', 'maps')):
            if c[k]:
                md.append(f"- {label}: {fmt(c[k])}")
        if c['key_doors']:
            md.append('- Key doors: ' + '; '.join(f"→R{d['to']} ({d['key']})" for d in c['key_doors']))
        if c['locked_doors']:
            md.append('- Locked doors: ' + '; '.join(f"→R{d['to']}" for d in c['locked_doors']))
        if c['puzzles']:
            md.append('- Item use: ' + '; '.join(sorted({p['item'] for p in c['puzzles']})))
        if c['typewriters'] or c['item_boxes']:
            md.append(f"- Typewriter: {len(c['typewriters'])}, item box: {len(c['item_boxes'])}")
        if c['enemies']:
            md.append('- Enemies: ' + ', '.join(f"{k} {v}" for k, v in sorted(c['enemies'].items())))
        md.append('')
    (ROOT / 'docs/room-catalog.md').write_text('\n'.join(md))
    print(len(cat), 'locations')


if __name__ == '__main__':
    main()
