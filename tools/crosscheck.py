"""Cross-check SCD-extracted room contents against Evil Resource per difficulty.

Writes docs/data-crosscheck.md and data/crosscheck.json.
Difficulty: bank0 bit23 set = Easy (verified: clock tower main hall Mine Thrower is Hard-only
under `if (ck(0, 23, 0))`, matching Evil Resource). Ink Ribbons carry no SCD guard but are
Hard-only on Evil Resource, so they are treated as Hard-only here (runtime rule to verify).
"""
import json, re, sys, collections
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from match_rooms import canon

ENEMY = {'ZOMBIE_DOG': 'zombie dog', 'CROW': 'crow', 'BS23': 'brain sucker', 'BS28': 'drain deimos',
         'MINI_BRAINSUCKER': 'brain sucker', 'HUNTER': 'hunter beta', 'HUNTER_GAMMA': 'hunter gamma',
         'SPIDER': 'giant spider', 'MINI_SPIDER': 'small spiders', 'SLIDING_WORM': 'sliding worm',
         'GRAVE_DIGGER': 'grave digger', 'NEMESIS': 'nemesis', 'NEMESIS_3': 'nemesis'}


def enemy_kind(t):
    t = t.replace('ENEMY_', '')
    if t.startswith('ZOMBIE_') and t != 'ZOMBIE_DOG':
        return 'zombie'
    return ENEMY.get(t)


def mode_of(cond):
    for c in cond:
        if c == 'if (ck(0, 23, 0))' or c == 'else[if (ck(0, 23, 1))]':
            return 'Hard'
        if c == 'if (ck(0, 23, 1))' or c == 'else[if (ck(0, 23, 0))]':
            return 'Easy'
    return None


def scd(rooms, rids, mode):
    items, enemies, cond = collections.Counter(), set(), set()
    for rid in rids:
        r = rooms.get(rid, {})
        for i in r.get('items', []):
            m = mode_of(i['cond']) or ('Hard' if i['name'] == 'Ink Ribbon' else None)
            if m not in (None, mode) or i['name'].endswith(' Map') or i['path'] is None:
                continue  # path None = procedure never referenced (dead code)
            items[canon(i['name'])] += 1
            if [c for c in i['cond'] if '(0, 23' not in c]:
                cond.add(canon(i['name']))
        for e in r.get('enemies', []):
            k = enemy_kind(e['type'])
            if k and k != 'nemesis' and e['path'] is not None and mode_of(e['cond']) in (None, mode):
                enemies.add(k)
    return items, enemies, cond


def er(room, mode):
    items, enemies, notes = collections.Counter(), set(), {}
    for x in room['contents']:
        if x['mode'] != mode:
            continue
        n = canon(x['name'])
        if x['kind'] in ('items', 'weaponry', 'files'):
            items[n] += 1
            notes[n] = x['note']
        elif x['kind'] == 'enemies' or (x['kind'] is None and re.search(r'zombie|deimos|sucker|hunter|spider|worm|crow', n)):
            n = re.sub(r"'s$", 's', n)
            n = {'zombies': 'zombie', 'zombie dogs': 'zombie dog', 'crows': 'crow', 'brain suckers': 'brain sucker',
                 'hunter betas': 'hunter beta', 'hunter gammas': 'hunter gamma', 'giant spiders': 'giant spider',
                 'sliding worms': 'sliding worm'}.get(n, n)
            if n != 'nemesis':
                enemies.add(n)
    return items, enemies, notes


def main():
    ids = json.loads((ROOT / 'data/room-ids.json').read_text())
    ers = {r['key']: r for r in json.loads((ROOT / 'data/evilresource-rooms.json').read_text())}
    rooms = json.loads((ROOT / 'data/rooms-DATA_J.json').read_text())
    by = collections.defaultdict(list)
    for rid, k in ids.items():
        by[k].append(rid)
    report, lines = [], ['# SCD ↔ Evil Resource cross-check', '',
                         'Generated by `tools/crosscheck.py`. SCD = DATA_J room scripts (all variants of a location merged). '
                         'Items compared as name sets; quantity differences between variants are not errors. '
                         '`cond` = SCD item has a story/random guard besides difficulty.', '']
    notes = json.loads((ROOT / 'data/crosscheck-notes.json').read_text())
    totals = collections.Counter()
    for key in sorted(by):
        for mode in ('Easy', 'Hard'):
            si, se, sc = scd(rooms, by[key], mode)
            ei, ee, _ = er(ers[key], mode)
            known = notes.get(key, {})
            only_scd = sorted(x for x in set(si) - set(ei) if x not in known)
            only_er = sorted(x for x in set(ei) - set(si) if x not in known)
            en_scd = sorted(x for x in se - ee if x not in known)
            en_er = sorted(x for x in ee - se if x not in known)
            ok = not (only_scd or only_er)
            totals['rooms'] += 1
            totals['items_ok' if ok else 'items_diff'] += 1
            totals['enemies_ok' if not (en_scd or en_er) else 'enemies_diff'] += 1
            report.append(dict(er=key, rooms=by[key], mode=mode, items_only_scd=only_scd, items_only_er=only_er,
                               enemies_only_scd=en_scd, enemies_only_er=en_er, conditional=sorted(sc)))
            if not ok or en_scd or en_er:
                lines.append(f"- **{ers[key]['title'].split(' (')[0]}** {by[key]} {mode}: "
                             + (f"items SCD-only {only_scd} ER-only {only_er}; " if not ok else '')
                             + (f"enemies SCD-only {en_scd} ER-only {en_er}" if en_scd or en_er else ''))
    lines += ['', '## Explained differences (data/crosscheck-notes.json)', '']
    lines += [f"- {k.split('/')[-1]} / {n}: {why}" for k, v in sorted(notes.items()) for n, why in sorted(v.items())]
    lines[4:4] = [f"Summary: {totals['rooms']} location×mode rows; items match {totals['items_ok']}, differ "
                  f"{totals['items_diff']}; enemy types match {totals['enemies_ok']}, differ {totals['enemies_diff']}.", '']
    (ROOT / 'data/crosscheck.json').write_text(json.dumps(report, indent=1) + '\n')
    (ROOT / 'docs/data-crosscheck.md').write_text('\n'.join(lines) + '\n')
    print(dict(totals))


if __name__ == '__main__':
    main()
